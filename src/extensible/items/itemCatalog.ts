export type ElementType = 'physical' | 'fire' | 'ice' | 'nature' | 'void';
export type SkillCategory = 'attack' | 'heal' | 'buff' | 'debuff';

export interface WeaponItem {
  id: string;
  name: string;
  kind: 'weapon';
  spriteId: string;
  atk: number;
  element: ElementType;
  salvageGold: number;
  description: string;
  /** Optional combat effect (EFFECT_REGISTRY id), fired like a relic effect while equipped. */
  effectId?: string;
}

export interface ArmorItem {
  id: string;
  name: string;
  kind: 'armor';
  spriteId: string;
  def: number;
  maxHpBonus: number;
  salvageGold: number;
  description: string;
  /** Optional combat effect (EFFECT_REGISTRY id), fired like a relic effect while equipped. */
  effectId?: string;
  /**
   * Persistent attack modifier applied while this armor is equipped
   * (e.g. -5 for a cursed heavy plate). Added to the weapon's ATK when
   * a battle session is created; not a status, so it never expires.
   */
  atkDelta?: number;
}

export interface SkillStatusPayload {
  target: 'self' | 'enemy';
  statusId: string;
  value: number;
  duration: number;
}

export interface SkillItem {
  id: string;
  name: string;
  kind: 'skill';
  spriteId: string;
  category: SkillCategory;
  maxChargesPerBattle: number; // 1 to 3 uses per battle
  /**
   * 'single' (default): damage / enemy status hits the selected target only.
   * 'all_enemies': damage / enemy status hits every living enemy.
   */
  targetScope?: 'single' | 'all_enemies';
  damageMultiplier?: number;
  healPercent?: number;
  healFlat?: number;
  cleanse?: boolean;
  applyStatus?: SkillStatusPayload;
  salvageGold: number;
  description: string;
}

export interface ConsumableItem {
  id: string;
  name: string;
  kind: 'consumable';
  spriteId: string;
  maxCharges: number; // 2 to 3 scarce charges
  healPercent?: number;
  cleanse?: boolean;
  applyStatus?: SkillStatusPayload;
  description: string;
}

export interface RelicItem {
  id: string;
  name: string;
  kind: 'relic';
  spriteId: string;
  effectId: string;
  salvageGold: number;
  description: string;
}

export type AnyCatalogItem =
  | WeaponItem
  | ArmorItem
  | SkillItem
  | ConsumableItem
  | RelicItem;

